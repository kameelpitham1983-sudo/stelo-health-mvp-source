/*
# Central Case Management System

1. New Tables
- `cases` — Central case record linking every operational matter (pre-employment medicals, periodicals, transfers, travel/visa medicals, lab requests, specialist referrals, sickness absence, etc.) to companies, employees, workflows, appointments, medicals, providers, and documents.
  - `id` (uuid PK)
  - `case_reference` (text, unique) — STelo case reference e.g. STELO-20261031-0001
  - `case_type` (text) — one of: pre_employment, periodical, transfer, travel_medical, visa_medical, lab_request, specialist_referral, sickness_absence, other
  - `title` (text) — short description
  - `description` (text) — detailed case description
  - `company_id` (uuid FK → companies)
  - `company_name` (text)
  - `employee_id` (uuid FK → employees, nullable)
  - `employee_name` (text, nullable)
  - `assigned_coordinator` (text) — coordinator responsible
  - `case_owner` (text) — overall owner
  - `date_opened` (date)
  - `target_completion_date` (date, nullable)
  - `priority` (text) — low, medium, high, urgent
  - `status` (text) — new, active, awaiting_client_approval, awaiting_employee_info, awaiting_appointment, awaiting_provider, awaiting_clinical_review, awaiting_outcome, overdue, completed, on_hold, cancelled, exception
  - `next_action` (text, nullable)
  - `next_action_due_date` (date, nullable)
  - `linked_medical_id` (uuid FK → medicals, nullable)
  - `linked_appointment_id` (uuid FK → appointments, nullable)
  - `linked_travel_id` (uuid FK → travel_health, nullable)
  - `linked_sickness_id` (uuid FK → sickness_absence_cases, nullable)
  - `linked_workflow_instance_id` (uuid FK → workflow_instances, nullable)
  - `provider_id` (uuid FK → providers, nullable)
  - `provider_name` (text, nullable)
  - `laboratory_name` (text, nullable)
  - `specialist_name` (text, nullable)
  - `linked_document_ids` (jsonb, default []) — array of document IDs
  - `closure_notes` (text, nullable)
  - `closure_date` (date, nullable)
  - `created_by` (text)
  - `created_at` (timestamptz, default now())
  - `updated_at` (timestamptz, default now())

- `case_activity` — Chronological activity timeline for each case.
  - `id` (uuid PK)
  - `case_id` (uuid FK → cases)
  - `activity_type` (text) — created, status_change, note_added, document_uploaded, workflow_progress, appointment_scheduled, provider_update, clinical_review, completion, notification, assignment
  - `title` (text)
  - `description` (text, nullable)
  - `actor_name` (text)
  - `actor_role` (text)
  - `metadata` (jsonb, nullable)
  - `created_at` (timestamptz, default now())

2. Security
- Enable RLS on both tables.
- Grant CRUD to `authenticated` only (this is a signed-in app).
- Policies: company-scoped access — users can see cases for their company; admins and coordinators can see all cases; providers can see cases where they are the assigned provider; employers can see cases for their company only.
- `case_activity` inherits visibility from the parent case via EXISTS subquery.

3. Indexes
- Index on `cases.company_id`, `cases.status`, `cases.employee_id`, `cases.case_type`, `cases.assigned_coordinator`
- Index on `case_activity.case_id`

4. Important Notes
- This migration is purely additive — no existing tables are modified, no data is changed.
- The cases table links to existing records via FKs but does not cascade-delete to preserve data integrity.
- Case references are generated by the application layer using a STELO-YYYYMMDD-#### pattern.
*/

CREATE TABLE IF NOT EXISTS cases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_reference text UNIQUE NOT NULL,
  case_type text NOT NULL DEFAULT 'other',
  title text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  company_id uuid REFERENCES companies(id),
  company_name text NOT NULL DEFAULT '',
  employee_id uuid REFERENCES employees(id),
  employee_name text,
  assigned_coordinator text NOT NULL DEFAULT '',
  case_owner text NOT NULL DEFAULT '',
  date_opened date NOT NULL DEFAULT CURRENT_DATE,
  target_completion_date date,
  priority text NOT NULL DEFAULT 'medium',
  status text NOT NULL DEFAULT 'new',
  next_action text,
  next_action_due_date date,
  linked_medical_id uuid REFERENCES medicals(id),
  linked_appointment_id uuid REFERENCES appointments(id),
  linked_travel_id uuid REFERENCES travel_health(id),
  linked_sickness_id uuid REFERENCES sickness_absence_cases(id),
  linked_workflow_instance_id uuid REFERENCES workflow_instances(id),
  provider_id uuid REFERENCES providers(id),
  provider_name text,
  laboratory_name text,
  specialist_name text,
  linked_document_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  closure_notes text,
  closure_date date,
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE cases ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_cases_company_id ON cases(company_id);
CREATE INDEX IF NOT EXISTS idx_cases_status ON cases(status);
CREATE INDEX IF NOT EXISTS idx_cases_employee_id ON cases(employee_id);
CREATE INDEX IF NOT EXISTS idx_cases_case_type ON cases(case_type);
CREATE INDEX IF NOT EXISTS idx_cases_assigned_coordinator ON cases(assigned_coordinator);
CREATE INDEX IF NOT EXISTS idx_cases_priority ON cases(priority);

GRANT SELECT, INSERT, UPDATE, DELETE ON cases TO authenticated;

-- Admins and coordinators can see all cases
DROP POLICY IF EXISTS "admin_coordinator_select_cases" ON cases;
CREATE POLICY "admin_coordinator_select_cases"
ON cases FOR SELECT TO authenticated
USING (is_stelo_admin() OR user_role() IN ('coordinator'));

-- Admins and coordinators can create cases
DROP POLICY IF EXISTS "admin_coordinator_insert_cases" ON cases;
CREATE POLICY "admin_coordinator_insert_cases"
ON cases FOR INSERT TO authenticated
WITH CHECK (is_stelo_admin() OR user_role() IN ('coordinator'));

-- Admins and coordinators can update cases
DROP POLICY IF EXISTS "admin_coordinator_update_cases" ON cases;
CREATE POLICY "admin_coordinator_update_cases"
ON cases FOR UPDATE TO authenticated
USING (is_stelo_admin() OR user_role() IN ('coordinator'))
WITH CHECK (is_stelo_admin() OR user_role() IN ('coordinator'));

-- Admins can delete cases
DROP POLICY IF EXISTS "admin_delete_cases" ON cases;
CREATE POLICY "admin_delete_cases"
ON cases FOR DELETE TO authenticated
USING (is_stelo_admin());

-- Employers can see cases for their company
DROP POLICY IF EXISTS "employer_select_cases" ON cases;
CREATE POLICY "employer_select_cases"
ON cases FOR SELECT TO authenticated
USING (user_role() = 'employer' AND company_id IS NOT NULL AND company_id = user_company_id());

-- Providers can see cases where they are the assigned provider
DROP POLICY IF EXISTS "provider_select_cases" ON cases;
CREATE POLICY "provider_select_cases"
ON cases FOR SELECT TO authenticated
USING (user_role() = 'provider' AND provider_id IS NOT NULL AND provider_id = user_employee_id());

-- Employees can see their own cases
DROP POLICY IF EXISTS "employee_select_cases" ON cases;
CREATE POLICY "employee_select_cases"
ON cases FOR SELECT TO authenticated
USING (user_role() = 'employee' AND employee_id IS NOT NULL AND employee_id = user_employee_id());

-- Case Activity Table
CREATE TABLE IF NOT EXISTS case_activity (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_id uuid NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  activity_type text NOT NULL DEFAULT 'created',
  title text NOT NULL DEFAULT '',
  description text,
  actor_name text NOT NULL DEFAULT '',
  actor_role text NOT NULL DEFAULT '',
  metadata jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE case_activity ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_case_activity_case_id ON case_activity(case_id);
CREATE INDEX IF NOT EXISTS idx_case_activity_created_at ON case_activity(created_at);

GRANT SELECT, INSERT ON case_activity TO authenticated;

-- Case activity visibility mirrors parent case
DROP POLICY IF EXISTS "select_case_activity" ON case_activity;
CREATE POLICY "select_case_activity"
ON case_activity FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM cases
    WHERE cases.id = case_activity.case_id
    AND (
      is_stelo_admin()
      OR user_role() IN ('coordinator')
      OR (user_role() = 'employer' AND cases.company_id = user_company_id())
      OR (user_role() = 'provider' AND cases.provider_id = user_employee_id())
      OR (user_role() = 'employee' AND cases.employee_id = user_employee_id())
    )
  )
);

-- Admins and coordinators can add activity entries
DROP POLICY IF EXISTS "insert_case_activity" ON case_activity;
CREATE POLICY "insert_case_activity"
ON case_activity FOR INSERT TO authenticated
WITH CHECK (is_stelo_admin() OR user_role() IN ('coordinator', 'provider'));

-- Admins can update activity (for corrections)
DROP POLICY IF EXISTS "admin_update_case_activity" ON case_activity;
CREATE POLICY "admin_update_case_activity"
ON case_activity FOR UPDATE TO authenticated
USING (is_stelo_admin())
WITH CHECK (is_stelo_admin());

-- Admins can delete activity
DROP POLICY IF EXISTS "admin_delete_case_activity" ON case_activity;
CREATE POLICY "admin_delete_case_activity"
ON case_activity FOR DELETE TO authenticated
USING (is_stelo_admin());

-- Auto-update updated_at trigger
CREATE OR REPLACE FUNCTION update_cases_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_cases_updated_at ON cases;
CREATE TRIGGER trigger_cases_updated_at
BEFORE UPDATE ON cases
FOR EACH ROW EXECUTE FUNCTION update_cases_updated_at();
